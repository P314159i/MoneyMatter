// Synthetic fixtures used only to verify accounting, never user records.
const assert=require('node:assert/strict');
const L=require('../app/src/main/assets/ledger.js');
const old={version:1,currency:'EUR',spending:10000,savings:1000000,transactions:[]};
assert(L.valid(old));
assert.equal(L.savingsBySource(old).Unassigned,1000000);
const state={...old,savingsOrigins:[{name:'Mom',amount:450000},{name:'Mom',amount:550000}],transactions:[]};
assert(L.valid(state));assert.equal(L.savingsBySource(state).Mom,1000000);
const tx=(type,amount,source)=>({id:String(state.transactions.length),type,amount,label:'Test',date:'2026-10-20',savingsSource:source});
state.transactions.push(tx('savingsDeposit',10000,'Mom'),tx('withdraw',20000,'Mom'),tx('savingsExpense',5000,'Mom'),tx('save',1000,'My savings'));
assert(L.valid(state));let b=L.balances(state,'2026-10');
assert.equal(b.income,0);assert.equal(b.expenses,5000);assert.equal(b.withdrawals,25000);
assert.equal(L.savingsBySource(state).Mom,985000);
assert.equal(Object.values(L.savingsBySource(state)).reduce((a,b)=>a+b,0),b.savings);
assert(L.valid(JSON.parse(JSON.stringify(state))));
assert(!L.valid({...state,savingsOrigins:[{name:'Mom',amount:1}]}));
assert(!L.valid({...state,savingsOrigins:[{name:'',amount:1000000}]}));
state.transactions.push(tx('savingsDeposit',123,'__proto__'));
assert.equal(L.savingsBySource(state)['__proto__'],123);
state.transactions.push({id:'legacy',type:'save',amount:100,label:'Earlier transfer',date:'2026-09-01'});
assert.equal(L.savingsBySource(state).Unassigned,100);
assert.equal(Object.values(L.savingsBySource(state)).reduce((a,b)=>a+b,0),L.balances(state,'2026-09').savings);
state.transactions.pop();state.transactions.splice(1,1);
assert.equal(Object.values(L.savingsBySource(state)).reduce((a,b)=>a+b,0),L.balances(state,'2026-10').savings);
console.log('Savings source aggregation, legacy records, withdrawals, deposits, deletion and backup validation passed.');
